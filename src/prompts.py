# 3. Stage1 快速剪枝 Prompt（低延迟，max_new_tokens=10）
# ============================================================

SKIP_DECISION_PROMPT = """\
判断以下推理步骤是否可以跳过。

原始问题：{original_query}
当前步骤（hop_{hop_id}）：{hop_query}
已有上下文：{context_summary}

决策规则：
1. 若该步骤信息已完全包含在上下文中 → SKIP
2. 若该步骤是第一个 hop 或其他 hop 明确依赖它 → EXECUTE
3. 若该步骤与原始问题核心无关 → SKIP
4. 若不确定 → UNCERTAIN

只输出一个词：SKIP 或 EXECUTE 或 UNCERTAIN"""


