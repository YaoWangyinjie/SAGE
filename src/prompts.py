# ============================================================

IMPORTANCE_SCORING_PROMPT = """\
对以下推理步骤进行重要性评分，并给出你的预测答案。

原始问题：{original_query}
当前步骤（hop_{hop_id}）：{hop_query}
步骤工具：{tool_name}({tool_args})
已有上下文：{context_summary}
所有步骤概览：{all_hops_summary}

请按以下格式输出：

SPECULATION: <根据已知上下文，预测该步骤的可能答案，50字以内>
PREDICTION: <对该步骤结果的一句话预测>
SCORE: <重要性分数，0-100的整数>

评分标准：
- 80-100（ESSENTIAL）：对最终回答不可或缺，缺失则答案残缺
- 40-79（USEFUL）：有助于完善答案，但缺失仍可给出基本回答
- 0-39（REDUNDANT）：与最终目标高度重叠或关联极弱

示例输出：
SPECULATION: EAGLE 在量化兼容性和内存管理方面存在部署挑战
PREDICTION: 该步骤将揭示 EAGLE 的具体技术部署限制
SCORE: 85"""


